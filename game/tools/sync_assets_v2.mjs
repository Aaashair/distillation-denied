// OWNER: W5
// Sync v2 pixel assets into game/assets/v2 and generate
// src/config/assets_v2.generated.js. Tolerant of a missing manifest.
//
// Source search order (the worktree's ../assets/v2 is NOT the real tree):
//   1. <this game>/assets/v2
//   2. ../../assets/v2 from this file
//   3. ../assets/v2
//
// Usage: node tools/sync_assets_v2.mjs [--dry]
import { existsSync, mkdirSync, copyFileSync, readFileSync, writeFileSync, statSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dry = process.argv.includes('--dry');
const outJs = path.join(root, 'src/config/assets_v2.generated.js');
const dstRoot = path.join(root, 'assets/v2');

function emit(assets, voices) {
  const body = `// GENERATED by tools/sync_assets_v2.mjs — do not edit by hand.\n`
    + `// V2_ASSETS: manifest id -> { src, kind, size, frames, fps, loop, sheet }\n`
    + `// V2_VOICE_LINES: manifest id -> { src, zh, en, speaker, trigger, duration }\n`
    + `export const V2_ASSETS = ${JSON.stringify(assets, null, 1)};\n`
    + `export const V2_VOICE_LINES = ${JSON.stringify(voices, null, 1)};\n`;
  if (!dry) writeFileSync(outJs, body);
}

const SRC_CANDIDATES = [
  path.join(root, 'assets/v2'),
  path.resolve(root, '../../assets/v2'),
  path.resolve(root, '../assets/v2'),
];

function findSrcRoot() {
  for (const dir of SRC_CANDIDATES) {
    if (existsSync(path.join(dir, 'manifest.json'))) return dir;
  }
  for (const dir of SRC_CANDIDATES) {
    if (existsSync(dir)) return dir;
  }
  return SRC_CANDIDATES[0];
}

function asList(man) {
  if (!man) return [];
  if (Array.isArray(man)) return man;
  if (Array.isArray(man.assets)) return man.assets;
  if (Array.isArray(man.entries)) return man.entries;
  if (Array.isArray(man.files)) return man.files;
  if (man.assets && typeof man.assets === 'object' && !Array.isArray(man.assets)) {
    return Object.entries(man.assets).map(([id, v]) => (
      v && typeof v === 'object' ? Object.assign({ id }, v) : { id, path: v }
    ));
  }
  const firstArr = Object.values(man).find(Array.isArray);
  return firstArr || [];
}

const srcRoot = findSrcRoot();
const manPath = path.join(srcRoot, 'manifest.json');
if (!existsSync(manPath)) {
  console.log(`no manifest.json under ${srcRoot} — writing empty assets_v2.generated.js`);
  emit({}, {});
  process.exit(0);
}

const man = JSON.parse(readFileSync(manPath, 'utf8'));
const list = asList(man);
const assets = {};
const voices = {};
let copied = 0;
let bytes = 0;
let missing = 0;

for (const a of list) {
  if (!a || typeof a !== 'object') continue;
  const id = a.id || a.name || a.key;
  if (!id) continue;
  const kind = a.kind || a.type || a.category || '';
  if (kind === 'voice_design_preview' || kind === 'voice_design') continue;
  let rel = a.web || a.path || a.file || a.src || a.href;
  if (!rel || typeof rel !== 'string') continue;
  rel = rel.replace(/^assets\/v2\//, '').replace(/^\.\//, '');
  if (/\.ogg$/i.test(rel)) continue;
  const from = path.isAbsolute(rel) ? rel : path.join(srcRoot, rel);
  if (!existsSync(from)) {
    missing += 1;
    continue;
  }
  const toRel = rel.replace(/^\/+/, '');
  const to = path.join(dstRoot, toRel);
  if (!dry) {
    mkdirSync(path.dirname(to), { recursive: true });
    copyFileSync(from, to);
  }
  copied += 1;
  bytes += statSync(from).size;
  const src = `assets/v2/${toRel}`;
  if (kind === 'voice' || /\/voice\//.test(rel) || /^v2_vo_/.test(id)) {
    voices[id] = {
      src,
      zh: a.prompt || a.text || a.zh || '',
      en: a.subtitle_en || a.en || '',
      speaker: a.speaker || '',
      trigger: a.trigger || '',
      duration: a.duration || 0,
    };
  }
  const meta = { src, kind };
  for (const k of ['size', 'frames', 'fps', 'loop', 'sheet', 'speaker', 'trigger', 'duration', 'palette', 'note']) {
    if (a[k] != null) meta[k] = a[k];
  }
  assets[id] = meta;
}

emit(assets, voices);
console.log(
  `${dry ? '[dry] ' : ''}v2 assets from ${srcRoot}: ${copied} files `
  + `(${(bytes / 1048576).toFixed(1)} MB), ${Object.keys(voices).length} voice lines, ${missing} missing`,
);
