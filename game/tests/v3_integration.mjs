import { chromium } from 'playwright';
import fs from 'node:fs';
const url=process.argv[2]||'http://localhost:8091/';
const out=process.argv[3]||'test-output/v3/final';
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:720}});
const errors=[], rows=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`)});
function check(name,ok,detail=''){rows.push({name,ok:!!ok,detail});console.log(`${ok?'PASS':'FAIL'} ${name} ${detail}`)}
const shot=async name=>page.screenshot({path:`${out}/${name}.png`});
const state=()=>page.evaluate(()=>window.__debug.state());
await page.goto(url);await page.waitForFunction(()=>window.__debug);
for(const lang of ['en','zh']){
 await page.reload();await page.waitForFunction(()=>window.__debug);
 await Promise.all([page.waitForEvent('load'),page.locator(`[data-lang="${lang}"]`).click()]);await page.waitForFunction(()=>window.__debug);
 const title=await page.locator('.title-inner').innerText();
 check(`title ${lang} single language`,lang==='en'?!/[\u4e00-\u9fff]/.test(title.replaceAll('中文','')):title.includes('蒸馏圣堂'),title.slice(0,90));
 check(`choice ${lang} persists`,await page.evaluate(()=>localStorage.getItem('dd.lang.v3'))===lang);
 await shot(`title_${lang}`);
 await page.locator('#btn-start').click();await page.locator('#btn-disclaimer').click();await page.waitForTimeout(150);
 const select=await page.locator('#screen-select').innerText();
 check(`select ${lang} single language`,lang==='en'?!/[\u4e00-\u9fff]/.test(select):select.includes('开源之盾'));await shot(`select_${lang}`);
 await page.evaluate(()=>{window.__debug.startFight('deepseek');window.__debug.setGod(true)});await page.waitForTimeout(300);
 check(`fight ${lang} ready`,(await state()).state==='fight');await shot(`fight_${lang}`);
 await page.keyboard.press('p');await page.waitForTimeout(100);await shot(`debug_${lang}`);
 const debug=await page.locator('#debug-panel').innerText();
 check(`debug ${lang} selected language`,lang==='en'?!/[\u4e00-\u9fff]/.test(debug):debug.includes('调试'));
 await page.keyboard.press('p');
}
await page.keyboard.press('q');await page.waitForTimeout(150);
let s=await state();check('Q starts RTX independent timer',s.flasks.cooldowns.rtx5090>4 && s.flasks.cooldowns.h200===0&&s.flasks.cooldowns.b200===0,JSON.stringify(s.flasks));
await page.keyboard.press('Escape');await page.waitForFunction(()=>window.__debug.state().state==='paused');const before=(await state()).flasks.cooldowns.rtx5090;await page.waitForTimeout(700);const after=(await state()).flasks.cooldowns.rtx5090;
check('pause freezes cooldown',before===after,`${before} -> ${after}`);await shot('gpu_paused');
await page.evaluate(()=>window.__debug.startFight('deepseek'));s=await state();
check('retry resets cooldowns',Object.values(s.flasks.cooldowns).every(x=>x===0),JSON.stringify(s.flasks));
check('no quantity contract',!('charges' in s.flasks));
await page.evaluate(()=>{window.__debug.setGod(true);window.__debug.setPhase(1)});await page.waitForTimeout(4200);await shot('haiku_dario_idle');
const portrait=await page.locator('.dario-portrait').evaluate(el=>({loaded:el.complete&&el.naturalWidth>0}));check('Dario portrait resource loaded; idle arena screenshot saved',portrait.loaded,JSON.stringify(portrait));
await page.evaluate(()=>{window.__debug.startFight('deepseek');window.__debug.setPhase(1);window.__debug.killPlayer()});await page.waitForTimeout(1200);
check('Haiku death ban screen',(await state()).state==='banned');await shot('ban_zh');
await page.evaluate(()=>{window.__debug.startFight('kimi');window.__debug.setPhase(3);window.__debug.killPlayer()});await page.waitForTimeout(200);
check('Opus death ending A route',(await state()).ending==='A',JSON.stringify((await state()).cutscene));
await page.evaluate(()=>window.__debug.triggerEnding('B'));await page.waitForTimeout(200);check('ending B trigger route',(await state()).ending==='B');
check('browser console and HTTP clean',errors.length===0,errors.join(' | '));
const pass=rows.filter(r=>r.ok).length,fail=rows.length-pass;
fs.writeFileSync(`${out}/integration.json`,JSON.stringify({url,pass,fail,errors,rows,assists:'debug startFight/setGod/setPhase/killPlayer/triggerEnding. Q and pause are real keyboard inputs. Not a human playtest.'},null,2));
fs.writeFileSync(`${out}/integration.txt`,rows.map(r=>`${r.ok?'PASS':'FAIL'} ${r.name} ${r.detail}`).join('\n')+`\nTOTAL ${pass} PASS / ${fail} FAIL\n`);
await browser.close();console.log(`TOTAL ${pass} PASS / ${fail} FAIL`);process.exitCode=fail?1:0;
