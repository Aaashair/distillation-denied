export const GLYPH_W = 3;
export const GLYPH_H = 5;
export const GLYPH5_W = 5;
export const GLYPH5_H = 7;

function blitGlyph(g, rows, x, y, px) {
  for (let row = 0; row < rows.length; row += 1) {
    const line = rows[row];
    for (let col = 0; col < line.length; col += 1) {
      if (line[col] === '1') g.fillRect(x + col * px, y + row * px, px, px);
    }
  }
}

function drawWith(g, table, gw, gh, text, x, y, color, scale) {
  const s = text == null ? '' : String(text).toUpperCase();
  const px = Math.max(1, scale | 0);
  g.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (let i = 0; i < s.length; i += 1) {
    const rows = table[s[i]] || table[s[i].toUpperCase()];
    if (!rows) {
      cx += (gw + 1) * px;
      continue;
    }
    blitGlyph(g, rows, cx, cy, px);
    cx += (gw + 1) * px;
  }
  return { w: cx - Math.round(x), h: gh * px };
}

/**
 * 3×5 bitmap. `scale` is integer pixel size of one glyph pixel.
 */
export function drawText(g, text, x, y, color = '#f4f1ea', scale = 1) {
  return drawWith(g, G3, GLYPH_W, GLYPH_H, text, x, y, color, scale);
}

/** 5×7 bitmap — damage numbers, banners. */
export function drawText5(g, text, x, y, color = '#f4f1ea', scale = 1) {
  return drawWith(g, G5, GLYPH5_W, GLYPH5_H, text, x, y, color, scale);
}

/** Dark 1px outline then fill — readable on any floor. */
export function drawTextOutlined(g, text, x, y, color, scale, big) {
  const fn = big ? drawText5 : drawText;
  const ink = '#1b1530';
  const px = Math.round(x);
  const py = Math.round(y);
  fn(g, text, px - 1, py, ink, scale);
  fn(g, text, px + 1, py, ink, scale);
  fn(g, text, px, py - 1, ink, scale);
  fn(g, text, px, py + 1, ink, scale);
  return fn(g, text, px, py, color, scale);
}

export function measure(text, scale = 1) {
  const n = text == null ? 0 : String(text).length;
  const px = Math.max(1, scale | 0);
  return { w: Math.max(0, n * (GLYPH_W + 1) * px - px), h: GLYPH_H * px };
}

export function measure5(text, scale = 1) {
  const n = text == null ? 0 : String(text).length;
  const px = Math.max(1, scale | 0);
  return { w: Math.max(0, n * (GLYPH5_W + 1) * px - px), h: GLYPH5_H * px };
}

/**
 * Tiny CJK (or mixed) label. Integer position. May be slightly soft at 3×
 * — English gameplay text should use drawText / drawText5 instead.
 */
export function drawCjk(g, text, x, y, color = '#f4f1ea', size = 8) {
  if (!text) return;
  g.save();
  g.imageSmoothingEnabled = false;
  g.fillStyle = color;
  g.font = `${size | 0}px "Songti SC","Noto Sans SC","PingFang SC",sans-serif`;
  g.textBaseline = 'top';
  g.fillText(String(text), Math.round(x), Math.round(y));
  g.restore();
}

/** Bilingual stack: English bitmap + Chinese fillText under it. */
export function drawBilingual(g, en, zh, x, y, color = '#f4f1ea', scale = 1) {
  const m = drawTextOutlined(g, en, x, y, color, scale, false);
  if (zh) drawCjk(g, zh, x, y + m.h + 2, color, 8);
  return m;
}

